from __future__ import annotations

import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path

from app.media import audio, background, subtitles
from app.media.ffprobe import MediaInfo


class FFmpegError(RuntimeError):
    pass


def ffmpeg_path() -> str:
    path = shutil.which("ffmpeg")
    if not path:
        raise FFmpegError("ffmpeg не найден в PATH")
    return path


def run(args: list[str], timeout: int = 1800) -> None:
    cmd = [ffmpeg_path(), "-hide_banner", "-nostdin", "-loglevel", "error", "-y", *args]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired as exc:
        raise FFmpegError("ffmpeg timeout") from exc
    if proc.returncode != 0:
        raise FFmpegError(proc.stderr.strip()[-800:] or f"ffmpeg exit code {proc.returncode}")


@dataclass
class RenderResult:
    profile: str
    burned_subtitles: bool


def output_fps(src_fps: float, cfg: dict) -> str:
    """fps: source keeps the source frame rate up to max_fps; otherwise (unknown, too high) fallback_fps."""
    if str(cfg.get("fps", "source")) != "source":
        return str(cfg["fps"])
    if src_fps and 0 < src_fps <= float(cfg.get("max_fps", 60)) + 0.01:
        return f"{src_fps:.3f}".rstrip("0").rstrip(".")
    return str(cfg.get("fallback_fps", 30))


def render_vertical(src: Path, out: Path, info: MediaInfo, cfg: dict, sub_cfg: dict,
                    cues: list[subtitles.Cue] | None, workdir: Path) -> RenderResult:
    """Source → WxH H.264/AAC MP4: 9:16 framing, original (normalised) audio, optional burned subtitles."""
    w, h = int(cfg["width"]), int(cfg["height"])
    fps = output_fps(info.fps, cfg)
    graph, profile = background.base_graph(
        cfg.get("mode", "blur"), info.width, info.height, w, h,
        float(cfg.get("vertical_tolerance", 0.08)),
        int(cfg.get("background_blur", 20)), float(cfg.get("background_darken", 0.15)),
        str(cfg.get("scale_flags", "lanczos")),
    )
    inputs = ["-i", str(src)]
    next_input = 1
    silent_input = None
    if not info.has_audio and cfg.get("add_silent_audio_if_missing", True):
        inputs += ["-f", "lavfi", "-i", "anullsrc=channel_layout=stereo:sample_rate=48000"]
        silent_input = next_input
        next_input += 1

    label = "vbase"
    burned = False
    if cues:
        overlays = subtitles.build_overlays(cues, workdir / "subs", w, h, sub_cfg)
        for png, *_ in overlays:
            inputs += ["-i", str(png)]
        sub_graph, label = subtitles.overlay_graph(overlays, w, next_input, label)
        graph += ";" + sub_graph
        burned = True
        profile += "+subtitles"
    graph += f";[{label}]fps={fps},format=yuv420p[vout]"

    maps = ["-map", "[vout]"]
    audio_args: list[str] = []
    if info.has_audio:
        maps += ["-map", "0:a:0"]
        audio_args = ["-af", audio.loudnorm(float(cfg.get("loudness_target", -14)))]
    elif silent_input is not None:
        maps += ["-map", f"{silent_input}:a:0"]
    if info.has_audio or silent_input is not None:
        audio_args += ["-c:a", "aac", "-b:a", str(cfg.get("audio_bitrate", "256k")), "-ar", "48000", "-ac", "2"]

    graph_file = workdir / "graph.txt"
    graph_file.write_text(graph, encoding="utf-8")
    run([
        *inputs,
        "-filter_complex_script", str(graph_file),
        *maps,
        "-t", f"{info.duration:.3f}",
        "-c:v", "libx264", "-preset", str(cfg.get("preset", "medium")), "-crf", str(cfg.get("crf", 17)),
        "-profile:v", "high", "-pix_fmt", "yuv420p", "-r", str(fps),
        *audio_args,
        "-movflags", "+faststart",
        str(out),
    ])
    return RenderResult(profile=profile, burned_subtitles=burned)


def thumbnail(video: Path, out: Path, at: float, width: int) -> None:
    run(["-ss", f"{max(at, 0):.3f}", "-i", str(video), "-frames:v", "1",
         "-vf", f"scale={width}:-2", "-q:v", "3", str(out)])


def gray_frame(video: Path, at: float, size: int = 32) -> bytes:
    """Raw size×size 8-bit grayscale frame, used for perceptual hashing."""
    cmd = [ffmpeg_path(), "-hide_banner", "-nostdin", "-loglevel", "error", "-ss", f"{at:.3f}", "-i", str(video),
           "-frames:v", "1", "-vf", f"scale={size}:{size}:flags=area,format=gray", "-f", "rawvideo", "-"]
    proc = subprocess.run(cmd, capture_output=True, timeout=120)
    if proc.returncode != 0 or len(proc.stdout) < size * size:
        raise FFmpegError(f"не удалось извлечь кадр {at:.2f}s: {proc.stderr.decode(errors='replace')[-300:]}")
    return proc.stdout[: size * size]


def make_test_video(out: Path, width: int = 1920, height: int = 1080, duration: float = 8.0,
                    with_audio: bool = True, pattern: str = "testsrc2", freq: int = 440) -> Path:
    """Synthetic clip generated by FFmpeg itself (no downloads needed)."""
    out.parent.mkdir(parents=True, exist_ok=True)
    args = ["-f", "lavfi", "-i", f"{pattern}=size={width}x{height}:rate=30"]
    if with_audio:
        args += ["-f", "lavfi", "-i", f"sine=frequency={freq}:sample_rate=48000:duration={duration}"]
    args += ["-t", f"{duration}", "-c:v", "libx264", "-preset", "veryfast", "-pix_fmt", "yuv420p"]
    if with_audio:
        args += ["-c:a", "aac"]
    run([*args, str(out)])
    return out
